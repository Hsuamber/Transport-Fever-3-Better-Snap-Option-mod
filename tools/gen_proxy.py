"""Generate the vulkan-1.dll proxy's export stubs from a real Vulkan loader.

usage: python tools/gen_proxy.py [C:\Windows\System32\vulkan-1.dll]
writes src/proxy/exports.S, src/proxy/exports_gen.c, src/proxy/vulkan-1.def

Each export is a 6-byte `jmp *slot(%rip)`; proxy.c fills the slots from the system loader at load time.
"""
import os
import sys

import pefile

src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32", "vulkan-1.dll")
pe = pefile.PE(src, fast_load=True)
pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]])
names = sorted({e.name.decode() for e in pe.DIRECTORY_ENTRY_EXPORT.symbols if e.name})
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "proxy")

with open(os.path.join(here, "exports.S"), "w", newline="\n") as f:
    f.write("# generated by tools/gen_proxy.py from %s (%d exports)\n" % (os.path.basename(src), len(names)))
    f.write("    .text\n")
    for i, n in enumerate(names):
        f.write("    .globl %s\n    .p2align 3\n%s:\n    jmp *tf3_vk_slots+%d(%%rip)\n" % (n, n, 8 * i))
with open(os.path.join(here, "exports_gen.c"), "w", newline="\n") as f:
    f.write("/* generated by tools/gen_proxy.py */\n")
    f.write("const unsigned tf3_vk_count = %d;\n" % len(names))
    f.write("void *tf3_vk_slots[%d];\n" % len(names))
    f.write("const char *const tf3_vk_names[%d] = {\n" % len(names))
    for n in names:
        f.write('    "%s",\n' % n)
    f.write("};\n")
with open(os.path.join(here, "vulkan-1.def"), "w", newline="\n") as f:
    f.write("LIBRARY \"vulkan-1.dll\"\nEXPORTS\n")
    for n in names:
        f.write("    %s\n" % n)
print("%d exports from %s" % (len(names), src))
