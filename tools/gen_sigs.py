"""Generate byte signatures (with wildcards) for the game functions the plugin hooks.

usage: python tools/gen_sigs.py "<path to TransportFever3.exe>" > src/plugin/sigs.inc

For every target the signature is the function's first N bytes with every rip-relative displacement,
call/jmp target and absolute-address immediate masked out, grown until it matches exactly once in .text.
Needs: pip install pefile capstone
"""
import sys

import capstone
import pefile
from capstone import x86_const as X

TARGETS = [  # (id, rva in the reference build, what it is)
    ("CalcCursorPoint", 0x571820, "UI::anon::CalcCursorPoint"),
    ("FindSnapPointBaseEdge", 0x60C360, "street_util::FindSnapPointBaseEdge"),
    ("MyFindSnapPointNew", 0x5FB370, "anon::MyFindSnapPointNew"),
    ("RoadEarlyAbort", 0x60D090, "road candidate early-abort check (ctx: +8 snapDist, +0xc nodeGap)"),
    ("TrackNearScore", 0x605A10, "FindSnapPointBaseEdge::<lambda_2> (captures: +0x40 radius, +0x44 nodeGap)"),
    ("TrackFarScore", 0x606B50, "FindSnapPointBaseEdge::<lambda_4> (captures: +0x40 radius, +0x44 nodeGap)"),
    ("CollectNodesAndEdges", 0x60B370, "candidate pick cone query (6th arg = radius px)"),
    ("GetSnapTangents", 0x57DCC0, "angle-alignment candidates (vector<TangentCandidate>)"),
    ("StreetBuilderStep", 0x585E50, "UI::StreetBuilder::Step (road & track tool, every frame)"),
    ("OperatorNew", 0x3184230, "game's operator new"),
    ("OperatorDelete", 0x318426C, "game's sized operator delete"),
    # cross-alignment guide (optional: missing ones only disable that feature)
    ("UpdateRenderer", 0x58A100, "UI::StreetBuilder::UpdateRenderer (once per Step)"),
    ("DrawEdges", 0x7B9130, "line renderer: (renderer, vector<Edge0x40>*, float width, float4* colA, float4* colB)"),
    ("MakeStraightEdge", 0x2BE1F50, "transport::MakeStraightEdge(out 0x40, p0*, p1*)"),
    ("GetComponentTypeIndex", 0xA4CC0, "ecs::ComponentManager::GetComponentTypeIndex(engine+0x48, type_info**)"),
    ("ComponentData", 0x95530, "ecs::Engine::GetComponentData<BaseEdge> (engine, entity, typeIndex) - stride 0x118 is built in"),
    ("HeightAt", 0x388660, "terrain height (terrain, xy*) -> float"),
    ("SnapPointPos", 0x60F770, "SnapPoint -> world position (out xyz, engine, SnapPoint*, useCache)"),
]

md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
md.detail = True


def masked(code, rva, max_bytes):
    out = []
    for ins in md.disasm(code, rva):
        b = list(ins.bytes)
        mask = [True] * len(b)
        if ins.disp_size and ins.disp_offset and any(
                op.type == X.X86_OP_MEM and op.mem.base == X.X86_REG_RIP for op in ins.operands):
            for k in range(ins.disp_offset, ins.disp_offset + ins.disp_size):
                mask[k] = False
        if (ins.group(X.X86_GRP_CALL) or ins.group(X.X86_GRP_JUMP)) and ins.imm_size == 4:
            for k in range(ins.imm_offset, ins.imm_offset + 4):
                mask[k] = False
        if ins.mnemonic == "movabs" or (ins.imm_size == 4 and any(
                op.type == X.X86_OP_IMM and 0x140000000 <= (op.imm & 0xFFFFFFFFFFFF) < 0x150000000 for op in ins.operands)):
            for k in range(ins.imm_offset, ins.imm_offset + ins.imm_size):
                mask[k] = False
        out += [(v if m else None) for v, m in zip(b, mask)]
        if len(out) >= max_bytes:
            break
    return out


def count(text, pat, limit=2):
    """occurrences of pat (list with None wildcards) in text, stop at `limit`."""
    first = next(i for i, v in enumerate(pat) if v is not None)
    anchor = bytes([pat[first]])
    n, pos, hits = 0, 0, []
    while True:
        pos = text.find(anchor, pos)
        if pos < 0:
            return hits
        start = pos - first
        if start >= 0 and all(v is None or text[start + k] == v for k, v in enumerate(pat)):
            hits.append(start)
            if len(hits) >= limit:
                return hits
        pos += 1


def main():
    pe = pefile.PE(sys.argv[1], fast_load=True)
    text_sec = next(s for s in pe.sections if s.Name.rstrip(b"\0") == b".text")
    raw = pe.__data__
    text = bytes(raw[text_sec.PointerToRawData:text_sec.PointerToRawData + text_sec.SizeOfRawData])
    tbase = text_sec.VirtualAddress
    print("// generated by tools/gen_sigs.py from TransportFever3.exe (TimeDateStamp 0x%08x, SizeOfImage 0x%x)"
          % (pe.FILE_HEADER.TimeDateStamp, pe.OPTIONAL_HEADER.SizeOfImage))
    print("// SIG(id, reference_rva, \"pattern\")   ?? = wildcard")
    for name, rva, what in TARGETS:
        code = text[rva - tbase: rva - tbase + 256]
        for n in range(16, 200, 4):
            pat = masked(code, rva, n)[:n]
            hits = count(text, pat)
            if len(hits) == 1:
                break
        else:
            raise SystemExit("no unique signature for " + name)
        assert hits[0] + tbase == rva, (name, hex(hits[0] + tbase))
        s = " ".join("??" if v is None else "%02X" % v for v in pat)
        print("SIG(%s, 0x%X, \"%s\") // %s" % (name, rva, s, what))


main()
